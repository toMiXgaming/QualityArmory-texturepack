def blank():
    return Image.new('RGBA', (16, 16), (0, 0, 0, 0))

def put(img, x, y, ch):
    if 0 <= x < 16 and 0 <= y < 16 and PAL.get(ch):
        img.putpixel((x, y), PAL[ch] + (255,))

def diag(img, c, half, prof, ends=None, t0=None):
    """Pasek po przekątnej (lewy dół -> prawy góra). prof: kolory dla x+y = c, c+1, ..."""
    for y in range(16):
        for x in range(16):
            s = x + y - c
            t = x - y
            if 0 <= s < len(prof) and -half <= t <= half:
                ch = prof[s]
                if ends and (t <= -half + ends[1] - 1 or t >= half - ends[1] + 1):
                    ch = ends[0][s] if s < len(ends[0]) else ch
                put(img, x, y, ch)
    return img

def gear(img, cx, cy, r, teeth, body='3', dark='2', hole=1.4):
    for y in range(16):
        for x in range(16):
            dx, dy = x - cx, y - cy
            d = math.hypot(dx, dy)
            a = math.atan2(dy, dx)
            rr = r - 0.9 + (1.2 if math.cos(a * teeth) > 0.2 else 0)
            if hole < d <= rr:
                put(img, x, y, body if d < r - 1.3 else dark if math.cos(a*teeth) <= 0.2 else body)
    return img

